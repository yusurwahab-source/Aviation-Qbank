/**
 * Grading, both per question and for the finished test.
 *
 * Grading happens on the server for a reason: the page itself never carries
 * `correct` or `explanation`, so no amount of reading the source gets a
 * student the answers. `answerQuestion` below hands back one question's key
 * at a time, and only in reply to that question being answered.
 */

/**
 * There is deliberately no small ceiling here, to match the test builder: a
 * student may ask for every published question. 5000 exists only to bound a
 * hostile payload, the same way `parseTopics` bounds section names — it is
 * far past any bank this project seeds in one deploy.
 */
const MAX_ANSWERS = 5000;

const submissionSchema = z.object({
  aircraftCode: z.string().regex(/^[A-Z][A-Z0-9]{1,7}$/),
  /**
   * Generated by the browser when the test starts, and the same value on every
   * retry of this submission. It is what stops one test being recorded twice.
   */
  clientTestId: z.string().min(8).max(64),
  answers: z
    .array(
      z.object({
        questionId: z.string().max(40),
        selectedOptionId: z.string().max(4).nullable(),
      }),
    )
    .min(1)
    .max(MAX_ANSWERS),
});

export type SubmitTestInput = z.infer<typeof submissionSchema>;

/** How the result was stored, so the screen can say so honestly. */
export type SaveStatus =
  /** Written to the signed-in user's history. */
  | "saved"
  /** Already recorded — this was a repeat submission of the same test. */
  | "already-saved"
  /** Nobody is signed in, so there is nowhere to save it. */
  | "signed-out"
  /** Someone is signed in but the write failed. */
  | "failed";

export type SubmitTestOutput = TestResult & {
  saveStatus: SaveStatus;
  /**
   * How many of the reviewed questions had their answer withheld, and why.
   * Zero for a subscriber and for any student inside their allowance, which
   * is every ordinary test — see `entitledAnswerKeyIds` below.
   */
  withheld: { count: number; reason: "preview" | "free-tier" } | null;
};

export async function submitTest(input: SubmitTestInput): Promise<SubmitTestOutput> {
  const { aircraftCode, clientTestId, answers } = submissionSchema.parse(input);

  // The answer key is re-read from the database rather than trusted from the
  // client, and is scoped to this aircraft's published questions.
  const key = await getAnswerKey(
    aircraftCode,
    answers.map((answer) => answer.questionId),
  );

  if (key.length === 0) {
    throw new Error("Those questions could not be found. Please start a new test.");
  }

  // Preserve the order the user saw, which the client sends in `answers`.
  const keyById = new Map(key.map((question) => [question.id, question]));
  const ordered = answers
    .map((answer) => keyById.get(answer.questionId))
    .filter((question) => question !== undefined);

  const result = gradeTest(aircraftCode, ordered, answers);

  // Grading is over the whole test — the score, the topic breakdown and the
  // counts are the student's own results — but the key only goes back for
  // the questions they are entitled to. Without this, one submission naming
  // every published question returned every answer and every explanation,
  // to anybody, with no account.
  const entitlement = await entitledAnswerKeyIds(
    aircraftCode,
    result.graded.map((entry) => entry.question.id),
  );
  const withheldResult = withholdAnswerKey(result, entitlement.ids);
  const withheldCount = withheldResult.graded.filter((entry) => entry.withheld).length;

  return {
    ...withheldResult,
    saveStatus: await record(clientTestId, result),
    withheld:
      withheldCount > 0 && entitlement.reason !== null
        ? { count: withheldCount, reason: entitlement.reason }
        : null,
  };
}

/**
 * Which of a finished test's questions this caller may be shown the answer
 * to — and, if some are withheld, what to tell them about it.
 *
 * Three cases, each the same rule the rest of the app already applies, only
 * asked about a whole test at once instead of one question at a time:
 *
 *  - **Active subscription**: everything. Nothing is withheld, ever.
 *  - **Signed in, no subscription**: every question they have already
 *    answered — those spent a slot when they were answered and are paid for
 *    — plus as many of the rest as the free allowance still covers. A test
 *    is already capped to that allowance when it is built, so an ordinary
 *    student never reaches the edge of this; a submission naming more
 *    questions than the allowance does, and stops there.
 *  - **Signed out**: exactly the same shape against the preview allowance,
 *    and the extra questions it covers are *spent* here, because seeing an
 *    answer is what the preview is counted in. A visitor who left two of
 *    five blank still gets their full review; one who submits the bank gets
 *    what is left of five.
 *
 * The extras are taken in submission order, which is the order the student
 * saw them in — so a partial review reads top-down rather than in scattered
 * pieces.
 */
async function entitledAnswerKeyIds(
  aircraftCode: string,
  questionIds: string[],
): Promise<{ ids: Set<string>; reason: "preview" | "free-tier" | null }> {
  const all = (): { ids: Set<string>; reason: null } => ({
    ids: new Set(questionIds),
    reason: null,
  });

  try {
    const user = await getCurrentUser();

    if (user) {
      const subscription = await getSubscription(user.id);
      if (hasFullAccess(subscription)) return all();

      const [alreadyAnswered, distinctAnswered, settings] = await Promise.all([
        answeredQuestionIdsAmong(user.id, questionIds),
        countQuestionsAnswered(user.id, aircraftCode),
        getSiteSettings(),
      ]);

      const ids = extendWithinAllowance(
        questionIds,
        alreadyAnswered,
        remainingFreeQuestions(distinctAnswered, settings.freeQuestionsPerAircraft),
      );
      return { ids, reason: "free-tier" };
    }

    // Signed out. The address limit applies here exactly as it does to a
    // single answer, and for the same reason: the cookie below bounds an
    // honest visitor, and this bounds one who simply never sends it back.
    // Blocked means nothing is revealed — the score still stands.
    const ip = await getClientIp();
    const allowed = await checkPreviewAllowed(ip);
    if (!allowed.allowed) return { ids: new Set(), reason: "preview" };
    await recordPreviewRequest(ip);

    // No cookie yet means nothing has been previewed, which is the honest
    // starting point rather than a reason to refuse: they may still spend
    // the preview on this test's answers.
    const visitorId = await ensurePreviewVisitorId();
    const settings = await getSiteSettings();
    const [alreadyPreviewed, previewed] = await Promise.all([
      previewedQuestionIdsAmong(visitorId, questionIds),
      countPreviewQuestionsAnswered(visitorId, aircraftCode),
    ]);

    const ids = extendWithinAllowance(
      questionIds,
      alreadyPreviewed,
      remainingFreeQuestions(previewed, settings.previewQuestionsSignedOut),
    );

    // Spend what this review is about to reveal. Written before the result
    // goes back, the same ordering `answerQuestion` uses.
    const newlySpent = [...ids].filter((id) => !alreadyPreviewed.has(id));
    await recordPreviewAnswers(visitorId, aircraftCode, newlySpent);

    return { ids, reason: "preview" };
  } catch (error) {
    // Fail closed. A student who cannot be identified cannot be entitled,
    // and a database hiccup must never be the thing that hands out the key
    // — they still get their score, which needs no lookup at all.
    console.error("Failed to decide answer-key entitlement:", error);
    return { ids: new Set(), reason: null };
  }
}

/** The already-entitled ids, plus as many of the rest, in order, as the
 * remaining allowance covers. */
function extendWithinAllowance(
  questionIds: string[],
  alreadyEntitled: Set<string>,
  remaining: number,
): Set<string> {
  const ids = new Set(alreadyEntitled);
  let budget = Math.max(0, remaining);

  for (const questionId of questionIds) {
    if (budget === 0) break;
    if (ids.has(questionId)) continue;
    ids.add(questionId);
    budget -= 1;
  }

  return ids;
}

/**
 * Records the result for a signed-in user.
 *
 * A failure here must not cost the user their result — they answered the
 * questions and are entitled to see how they did. So the error is caught, the
 * result is still returned, and the screen says plainly that it was not saved.
 * Silently pretending it worked would be the worst of the three options.
 */
async function record(clientTestId: string, result: TestResult): Promise<SaveStatus> {
  try {
    const user = await getCurrentUser();
    if (!user) return "signed-out";

    const outcome = await recordTestResult(user.id, clientTestId, result);
    return outcome.status === "duplicate" ? "already-saved" : "saved";
  } catch (error) {
    console.error("Failed to record test result:", error);
    return "failed";
  }
}

const answerSchema = z.object({
  aircraftCode: z.string().regex(/^[A-Z][A-Z0-9]{1,7}$/),
  clientTestId: z.string().min(8).max(64),
  /** The full, ordered question set. Only used the first time this test is saved. */
  questionIds: z.array(z.string().max(40)).min(1).max(MAX_ANSWERS),
  questionId: z.string().max(40),
  selectedOptionId: z.string().max(4),
  /** Study marks as you go; exam holds everything back until Finish. */
  mode: z.enum(TEST_MODES),
  /** The sections this test was built from. Only used the first time this
   * test is saved, same as `questionIds` — bounded the same way
   * `parseTopics` bounds them, since this is the same untrusted shape. */
  topics: z.array(z.string().max(60)).max(50).default([]),
});

export type AnswerQuestionInput = z.infer<typeof answerSchema>;

/**
 * What answering one question tells the student back.
 *
 * `verdict` is the whole point: the correct option and the explanation, for
 * the one question they have just answered. Nothing else about the test comes
 * back with it.
 *
 * `saved` is bookkeeping the student never sees. Finish re-sends every answer
 * and that write is the authoritative one, so a dropped save mid-test is
 * something to log, not something to interrupt them about.
 */
export type AnswerVerdict = {
  isCorrect: boolean;
  correctOptionId: string;
  explanation: string;
  reference: string | null;
};

export type AnswerQuestionResult =
  /** `verdict` is present in study mode only; exam mode answers in silence. */
  | {
      status: "answered";
      verdict: AnswerVerdict | null;
      saved: AnswerSaveStatus;
      /**
       * When this test began, as the server reckons it. Study mode counts up
       * from here; it is also what the deadline below is derived from.
       */
      startedAt: string | null;
      /**
       * When this test runs out, as the server reckons it — the browser's
       * countdown syncs to this rather than trusting its own start time.
       * Null in study mode, which has no deadline, and for a signed-out
       * student, who has no session for the clock to live on.
       */
      expiresAt: string | null;
    }
  /** The question is not a real, published question on this aircraft. */
  | { status: "invalid" }
  /**
   * A new question on this aircraft, and the signed-in student has used up
   * the free allowance without an active subscription. Nothing is graded or
   * recorded — the question the free tier ends on is not itself given away.
   */
  | { status: "paywall" }
  /**
   * The signed-out equivalent: the visitor has spent their preview on this
   * aircraft and the answer is not theirs to see without an account. Same
   * shape as `paywall` and for the same reason — nothing is graded, nothing
   * is recorded, and the question they stopped on is not given away — but a
   * different destination, since what this asks for is a sign-up, not a
   * subscription.
   */
  | { status: "preview-exhausted" }
  /**
   * Too many signed-out answers from this address, too fast. Deliberately
   * distinguishable from the two above: those are a person reaching the end
   * of an allowance, this is a machine being told to slow down, and telling
   * a real visitor behind a shared address to "sign up" when the truth is
   * "wait a few minutes" would send them to the wrong place.
   */
  | { status: "rate-limited"; retryAfter: string }
  /** Nothing could be graded — the caller should leave the question open. */
  | { status: "failed" };

export type AnswerSaveStatus =
  | "recorded"
  /** Graded and shown, but nobody is signed in, so there is nowhere to save it. */
  | "signed-out"
  /** This test was already finished — a stray call from a stale tab. */
  | "closed"
  | "failed";

/**
 * Records one answer the moment it is given, and — in study mode — tells the
 * student how they did.
 *
 * This is the only path by which `correct` and `explanation` reach the
 * browser during a test, and it hands over exactly one question's worth,
 * in reply to that question actually being answered. There is no way to read
 * ahead with it: the answer you get back is for the question you just
 * committed to, and for a signed-in student that commitment is recorded
 * before the answer is returned.
 *
 * In exam mode nothing is returned but the acknowledgement. The answer is
 * still recorded — that is what a refresh resumes from and what an abandoned
 * test keeps — it simply is not shown until Finish.
 *
 * Grading re-reads the key from the database rather than trusting anything
 * the client claims, exactly as Finish does.
 *
 * Unlike recording, the marking runs for a signed-out student too — practice
 * without an account still teaches, it just leaves no history behind.
 */
export async function answerQuestion(
  input: AnswerQuestionInput,
): Promise<AnswerQuestionResult> {
  try {
    const {
      aircraftCode,
      clientTestId,
      questionIds,
      questionId,
      selectedOptionId,
      mode,
      topics,
    } = answerSchema.parse(input);

    // The clock is a consequence of the mode, not something the caller gets
    // to ask for: exam mode is a minute a question, study mode is untimed.
    // Nothing in the request can change that, so there is no longer anything
    // here to validate or to distrust.
    const timeLimitSeconds = timeLimitFor(mode, questionIds.length);

    const [question] = await getAnswerKey(aircraftCode, [questionId]);
    if (!question) return { status: "invalid" };

    const isCorrect = selectedOptionId === question.correct;
    // Built either way, because the recording needs `isCorrect` regardless —
    // but only handed back in study mode.
    const verdict: AnswerVerdict | null =
      mode === "study"
        ? {
            isCorrect,
            correctOptionId: question.correct,
            explanation: question.explanation,
            reference: question.reference,
          }
        : null;

    const user = await getCurrentUser();
    // Signed out there is no session, so no server-held clock. The browser's
    // own countdown is all there is — see the note in CLAUDE.md.
    //
    // What there *is* now is a limit. This branch used to return the verdict
    // to anybody at all, unmetered and unlimited, which made the whole
    // answer key readable by a script with no account: one request per
    // question, no cookie needed, nothing counting. A signed-out visitor now
    // gets a preview of the aircraft and no more, and the address they call
    // from is rate limited regardless of what cookie they present. Both
    // checks run *before* the verdict goes anywhere.
    if (!user) {
      const ip = await getClientIp();

      // The address limit first, and before any write: it is the one that
      // holds when the cookie below does not, and a caller being refused
      // should cost as little as possible — the same ordering log in uses
      // for the password check.
      const allowed = await checkPreviewAllowed(ip);
      if (!allowed.allowed) {
        return { status: "rate-limited", retryAfter: describeWait(allowed.retryAfterMs) };
      }
      await recordPreviewRequest(ip);

      const visitorId = await ensurePreviewVisitorId();
      const settings = await getSiteSettings();
      const [alreadyPreviewed, previewed] = await Promise.all([
        hasPreviewedQuestion(visitorId, questionId),
        countPreviewQuestionsAnswered(visitorId, aircraftCode),
      ]);

      // The same rule the free tier uses, with the preview's own limit: a
      // question already shown costs nothing to see again, and a new one
      // spends a slot.
      const mayPreview = canAnswerQuestion({
        hasSubscription: false,
        alreadyAnsweredThisQuestion: alreadyPreviewed,
        distinctAnsweredSoFar: previewed,
        limit: settings.previewQuestionsSignedOut,
      });
      if (!mayPreview) return { status: "preview-exhausted" };

      // Recorded before the verdict is returned, exactly as a signed-in
      // attempt is: asking to see an answer costs you the slot whether or
      // not you like what comes back.
      await recordPreviewAnswer(visitorId, questionId, aircraftCode);

      return { status: "answered", verdict, saved: "signed-out", startedAt: null, expiresAt: null };
    }

    // The free tier ends per aircraft, not per test — a subscriber skips
    // this entirely, and a non-subscriber may always revisit a question
    // already counted before, which is what makes retrying free.
    const subscription = await getSubscription(user.id);
    if (!hasFullAccess(subscription)) {
      const [alreadyAnswered, distinctAnswered, settings] = await Promise.all([
        hasAnsweredQuestionBefore(user.id, questionId),
        countQuestionsAnswered(user.id, aircraftCode),
        getSiteSettings(),
      ]);
      const allowed = canAnswerQuestion({
        hasSubscription: false,
        alreadyAnsweredThisQuestion: alreadyAnswered,
        distinctAnsweredSoFar: distinctAnswered,
        limit: settings.freeQuestionsPerAircraft,
      });
      if (!allowed) return { status: "paywall" };
    }

    // Recorded before the answer is returned, so the attempt is on file
    // whether or not the student likes what they see. A failure here loses
    // the record, never the verdict — they still get told how they did.
    let saved: AnswerSaveStatus;
    let startedAt: string | null = null;
    let expiresAt: string | null = null;
    try {
      const outcome = await saveAnswerRow({
        userId: user.id,
        clientTestId,
        aircraftCode,
        questionIds,
        questionCount: questionIds.length,
        questionId,
        topic: question.topic,
        selectedOptionId,
        isCorrect,
        timeLimitSeconds,
        mode,
        topics,
      });

      if (outcome.status === "recorded") {
        saved = "recorded";
        // Whatever this request computed, this is the clock that counts: the
        // one stored when the session was created. A test resumed after the
        // bank changed keeps the limit it started with.
        if (outcome.startedAt) {
          startedAt = outcome.startedAt.toISOString();
          if (outcome.timeLimitSeconds !== null) {
            expiresAt = deadlineFrom(outcome.startedAt, outcome.timeLimitSeconds).toISOString();
          }
        }
      } else if (outcome.status === "closed") {
        saved = "closed";
      } else {
        // "wrong-aircraft": the clientTestId in the URL belongs to a
        // different aircraft's session. Not reachable by normal navigation.
        saved = "failed";
      }
    } catch (error) {
      console.error("Failed to save an answer:", error);
      saved = "failed";
    }

    return { status: "answered", verdict, saved, startedAt, expiresAt };
  } catch (error) {
    console.error("Failed to answer a question:", error);
    return { status: "failed" };
  }
}

/* ────────────────────────── Flags and notes ───────────────────────────
 *
 * Both are signed-in only, and both fail quietly: a flag or a note is the
 * student's own study aid, not part of grading or history, so there is
 * nothing here worth interrupting a test over. The button that calls
 * `toggleFlag` has already updated itself optimistically before this
 * resolves; a failure here just means the next page load will not agree
 * with it, not that the test breaks.
 */

const flagSchema = z.object({
  questionId: z.string().max(40),
  aircraftCode: z.string().regex(/^[A-Z][A-Z0-9]{1,7}$/),
});

export async function toggleFlag(
  input: z.infer<typeof flagSchema>,
): Promise<{ flagged: boolean } | { status: "signed-out" | "failed" }> {
  try {
    const { questionId, aircraftCode } = flagSchema.parse(input);
    const user = await getCurrentUser();
    if (!user) return { status: "signed-out" };

    return await toggleQuestionFlag(user.id, questionId, aircraftCode);
  } catch (error) {
    console.error("Failed to toggle a flag:", error);
    return { status: "failed" };
  }
}

const noteSchema = z.object({
  questionId: z.string().max(40),
  aircraftCode: z.string().regex(/^[A-Z][A-Z0-9]{1,7}$/),
  body: z.string().max(4000),
});

export async function saveNote(
  input: z.infer<typeof noteSchema>,
): Promise<{ status: "saved" | "signed-out" | "failed" }> {
  try {
    const { questionId, aircraftCode, body } = noteSchema.parse(input);
    const user = await getCurrentUser();
    if (!user) return { status: "signed-out" };

    await saveQuestionNote(user.id, questionId, aircraftCode, body);
    return { status: "saved" };
  } catch (error) {
    console.error("Failed to save a note:", error);
    return { status: "failed" };
  }
}

/** Fetched lazily, the first time a question's note editor is opened —
 * loading every note for a whole test upfront does not scale to an
 * "all questions" test on a bank this size. */
export async function loadNote(questionId: string): Promise<string> {
  try {
    const user = await getCurrentUser();
    if (!user) return "";
    return (await getQuestionNote(user.id, questionId.slice(0, 40))) ?? "";
  } catch (error) {
    console.error("Failed to load a note:", error);
    return "";
  }
}

const REPORT_REASONS = ["wrong_answer", "unclear", "typo", "outdated", "other"] as const;

const reportSchema = z.object({
  questionId: z.string().max(40),
  reason: z.enum(REPORT_REASONS),
  comment: z.string().max(1000),
});

/**
 * "Report a problem" on the question currently on screen. Writes to
 * `question_reports` only — nothing here touches `questions` itself; fixing
 * a reported question is still the content-file-and-deploy workflow.
 *
 * Runs for a signed-out student too, the same as grading: practising
 * without an account still means reading a question that might be wrong,
 * and `userId` is nullable on this table for exactly that reason.
 */
export async function reportQuestion(
  input: z.infer<typeof reportSchema>,
): Promise<{ status: "reported" | "failed" }> {
  try {
    const { questionId, reason, comment } = reportSchema.parse(input);
    const user = await getCurrentUser();

    await createQuestionReport({
      questionId,
      userId: user?.id ?? null,
      reason,
      comment: comment.trim() === "" ? null : comment.trim(),
    });

    return { status: "reported" };
  } catch (error) {
    console.error("Failed to record a question report:", error);
    return { status: "failed" };
  }
}
