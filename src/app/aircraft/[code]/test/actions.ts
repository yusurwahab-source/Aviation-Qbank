"use server";

import { z } from "zod";

import { recordTestResult, saveAnswer as saveAnswerRow } from "@/db/attempts";
import { getAnswerKey } from "@/db/queries";
import { getCurrentUser } from "@/lib/auth/session";
import { gradeTest, type TestResult } from "@/lib/grading";
import { TEST_MODES, deadlineFrom } from "@/lib/test-options";

/**
 * Grading, both per question and for the finished test.
 *
 * Grading happens on the server for a reason: the page itself never carries
 * `correct` or `explanation`, so no amount of reading the source gets a
 * student the answers. `answerQuestion` below hands back one question's key
 * at a time, and only in reply to that question being answered.
 */

/**
 * There is deliberately no small ceiling here, to match the test builder: a
 * student may ask for every published question. 5000 exists only to bound a
 * hostile payload, the same way `parseTopics` bounds section names — it is
 * far past any bank this project seeds in one deploy.
 */
const MAX_ANSWERS = 5000;

const submissionSchema = z.object({
  aircraftCode: z.string().regex(/^[A-Z][A-Z0-9]{1,7}$/),
  /**
   * Generated by the browser when the test starts, and the same value on every
   * retry of this submission. It is what stops one test being recorded twice.
   */
  clientTestId: z.string().min(8).max(64),
  answers: z
    .array(
      z.object({
        questionId: z.string().max(40),
        selectedOptionId: z.string().max(4).nullable(),
      }),
    )
    .min(1)
    .max(MAX_ANSWERS),
});

export type SubmitTestInput = z.infer<typeof submissionSchema>;

/** How the result was stored, so the screen can say so honestly. */
export type SaveStatus =
  /** Written to the signed-in user's history. */
  | "saved"
  /** Already recorded — this was a repeat submission of the same test. */
  | "already-saved"
  /** Nobody is signed in, so there is nowhere to save it. */
  | "signed-out"
  /** Someone is signed in but the write failed. */
  | "failed";

export type SubmitTestOutput = TestResult & { saveStatus: SaveStatus };

export async function submitTest(input: SubmitTestInput): Promise<SubmitTestOutput> {
  const { aircraftCode, clientTestId, answers } = submissionSchema.parse(input);

  // The answer key is re-read from the database rather than trusted from the
  // client, and is scoped to this aircraft's published questions.
  const key = await getAnswerKey(
    aircraftCode,
    answers.map((answer) => answer.questionId),
  );

  if (key.length === 0) {
    throw new Error("Those questions could not be found. Please start a new test.");
  }

  // Preserve the order the user saw, which the client sends in `answers`.
  const keyById = new Map(key.map((question) => [question.id, question]));
  const ordered = answers
    .map((answer) => keyById.get(answer.questionId))
    .filter((question) => question !== undefined);

  const result = gradeTest(aircraftCode, ordered, answers);

  return { ...result, saveStatus: await record(clientTestId, result) };
}

/**
 * Records the result for a signed-in user.
 *
 * A failure here must not cost the user their result — they answered the
 * questions and are entitled to see how they did. So the error is caught, the
 * result is still returned, and the screen says plainly that it was not saved.
 * Silently pretending it worked would be the worst of the three options.
 */
async function record(clientTestId: string, result: TestResult): Promise<SaveStatus> {
  try {
    const user = await getCurrentUser();
    if (!user) return "signed-out";

    const outcome = await recordTestResult(user.id, clientTestId, result);
    return outcome.status === "duplicate" ? "already-saved" : "saved";
  } catch (error) {
    console.error("Failed to record test result:", error);
    return "failed";
  }
}

const answerSchema = z.object({
  aircraftCode: z.string().regex(/^[A-Z][A-Z0-9]{1,7}$/),
  clientTestId: z.string().min(8).max(64),
  /** The full, ordered question set. Only used the first time this test is saved. */
  questionIds: z.array(z.string().max(40)).min(1).max(MAX_ANSWERS),
  questionId: z.string().max(40),
  selectedOptionId: z.string().max(4),
  /** Study marks as you go; exam holds everything back until Finish. */
  mode: z.enum(TEST_MODES),
  /**
   * Seconds the student asked for, or null for untimed. Only read when the
   * session is created — after that the stored clock is the one that counts,
   * which is what stops a reload from asking for a fresh countdown.
   */
  timeLimitSeconds: z.number().int().positive().max(24 * 60 * 60).nullable(),
});

export type AnswerQuestionInput = z.infer<typeof answerSchema>;

/**
 * What answering one question tells the student back.
 *
 * `verdict` is the whole point: the correct option and the explanation, for
 * the one question they have just answered. Nothing else about the test comes
 * back with it.
 *
 * `saved` is bookkeeping the student never sees. Finish re-sends every answer
 * and that write is the authoritative one, so a dropped save mid-test is
 * something to log, not something to interrupt them about.
 */
export type AnswerVerdict = {
  isCorrect: boolean;
  correctOptionId: string;
  explanation: string;
  reference: string | null;
};

export type AnswerQuestionResult =
  /** `verdict` is present in study mode only; exam mode answers in silence. */
  | {
      status: "answered";
      verdict: AnswerVerdict | null;
      saved: AnswerSaveStatus;
      /**
       * When this test runs out, as the server reckons it — the browser's
       * countdown syncs to this rather than trusting its own start time.
       * Null on an untimed test, and for a signed-out student, who has no
       * session for the clock to live on.
       */
      expiresAt: string | null;
    }
  /** The question is not a real, published question on this aircraft. */
  | { status: "invalid" }
  /** Nothing could be graded — the caller should leave the question open. */
  | { status: "failed" };

export type AnswerSaveStatus =
  | "recorded"
  /** Graded and shown, but nobody is signed in, so there is nowhere to save it. */
  | "signed-out"
  /** This test was already finished — a stray call from a stale tab. */
  | "closed"
  | "failed";

/**
 * Records one answer the moment it is given, and — in study mode — tells the
 * student how they did.
 *
 * This is the only path by which `correct` and `explanation` reach the
 * browser during a test, and it hands over exactly one question's worth,
 * in reply to that question actually being answered. There is no way to read
 * ahead with it: the answer you get back is for the question you just
 * committed to, and for a signed-in student that commitment is recorded
 * before the answer is returned.
 *
 * In exam mode nothing is returned but the acknowledgement. The answer is
 * still recorded — that is what a refresh resumes from and what an abandoned
 * test keeps — it simply is not shown until Finish.
 *
 * Grading re-reads the key from the database rather than trusting anything
 * the client claims, exactly as Finish does.
 *
 * Unlike recording, the marking runs for a signed-out student too — practice
 * without an account still teaches, it just leaves no history behind.
 */
export async function answerQuestion(
  input: AnswerQuestionInput,
): Promise<AnswerQuestionResult> {
  try {
    const {
      aircraftCode,
      clientTestId,
      questionIds,
      questionId,
      selectedOptionId,
      mode,
      timeLimitSeconds,
    } = answerSchema.parse(input);

    const [question] = await getAnswerKey(aircraftCode, [questionId]);
    if (!question) return { status: "invalid" };

    const isCorrect = selectedOptionId === question.correct;
    // Built either way, because the recording needs `isCorrect` regardless —
    // but only handed back in study mode.
    const verdict: AnswerVerdict | null =
      mode === "study"
        ? {
            isCorrect,
            correctOptionId: question.correct,
            explanation: question.explanation,
            reference: question.reference,
          }
        : null;

    const user = await getCurrentUser();
    // Signed out there is no session, so no server-held clock. The browser's
    // own countdown is all there is — see the note in CLAUDE.md.
    if (!user) return { status: "answered", verdict, saved: "signed-out", expiresAt: null };

    // Recorded before the answer is returned, so the attempt is on file
    // whether or not the student likes what they see. A failure here loses
    // the record, never the verdict — they still get told how they did.
    let saved: AnswerSaveStatus;
    let expiresAt: string | null = null;
    try {
      const outcome = await saveAnswerRow({
        userId: user.id,
        clientTestId,
        aircraftCode,
        questionIds,
        questionCount: questionIds.length,
        questionId,
        topic: question.topic,
        selectedOptionId,
        isCorrect,
        timeLimitSeconds,
      });

      if (outcome.status === "recorded") {
        saved = "recorded";
        // Whatever the client asked for, this is the clock that counts: the
        // one stored when the session was created.
        if (outcome.startedAt && outcome.timeLimitSeconds !== null) {
          expiresAt = deadlineFrom(outcome.startedAt, outcome.timeLimitSeconds).toISOString();
        }
      } else if (outcome.status === "closed") {
        saved = "closed";
      } else {
        // "wrong-aircraft": the clientTestId in the URL belongs to a
        // different aircraft's session. Not reachable by normal navigation.
        saved = "failed";
      }
    } catch (error) {
      console.error("Failed to save an answer:", error);
      saved = "failed";
    }

    return { status: "answered", verdict, saved, expiresAt };
  } catch (error) {
    console.error("Failed to answer a question:", error);
    return { status: "failed" };
  }
}
